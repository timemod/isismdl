#' Returns included header files in a C source file or another C header file
#'
#' @param filename Character of length 1: the relative path of the file
#' (relative to `src_dir`).
#' @param src_dir The directory with source files.
#'
#' @return A character vector with the names of the included header files
#' (the relative path with respect to `src_dir`), or `NULL` if the file not
#' have any dependencies.
#'
#' @noRd
read_includes <- function(filename, src_dir) {
  src_path <- file.path(src_dir, filename)

  lines <- readLines(src_path, warn = FALSE)
  if (length(lines) == 0L) return(NULL)

  # Lines that look like include directives (quick filter)
  inc_lines <- grep("^\\s*#\\s*include\\s+", lines, value = TRUE, perl = TRUE)
  if (length(inc_lines) == 0L) return(NULL)

  # Quoted includes: #include "some/path.h"
  quoted <- grep('^\\s*#\\s*include\\s+"([^"]+)"', inc_lines, value = TRUE,
                 perl = TRUE)
  if (length(quoted) > 0) {
    quoted <- sub('^\\s*#\\s*include\\s+"([^"]+)".*$', "\\1",
                  quoted, perl = TRUE)
  }

  # Keep quoted includes only if they exist under src_dir
  if (length(quoted) > 0L) {
    exists_mask <- file.exists(file.path(src_dir, quoted))
    quoted <- quoted[exists_mask]
  }

  # Combine and return unique includes in alphabetic order.
  includes <- quoted
  if (length(includes) == 0L) return(NULL)
  includes <- sort(unique(includes))
  return(includes)
}

#' Returns a list with all dependencies of C and header files
#'
#' @param filenames Character: filenames of C and header files
#' @param src_dir The directory with source files.
#'
#' @returns A named list with the dependencies for each file.
#' @noRD
get_dep_list_c <- function(filenames, src_dir) {

  deps <- lapply(filenames, FUN = read_includes, src_dir = src_dir)
  names(deps) <- filenames

  # remove files without dependencies
  is_null <- sapply(deps, FUN = is.null)
  deps[!is_null]
}

#' Write a dependency file for C or Fortran files
#'
#' @param src_files Name of the source files (.c files).
#' @param dep_file Character: name of the dependency file.
#' @param g An `igraph` object with dependency information.
#' @param is_f90 Logical, `TRUE` for Fortran files
#' @noRd
write_dep_file <- function(src_files, dep_file, g, is_f90) {
  con <- file(dep_file, "wt")
  writeLines(
    "# This file is generated by 'tools/create_makedeps_files.R. Do not edit by hand!\n",
    con = con
  )
  for (src_file in src_files) {
    src_name <- tools::file_path_sans_ext(src_file)
    obj_file <- paste0(src_name, ".o")
    deps <- names(subcomponent(g, src_file, mode = "in")[-1])
    deps <- sort(deps)
    if (is_f90) deps <- paste0(deps, ".o")
    txt <- paste(obj_file, ":", paste(deps, collapse = " "))
    lines <- strwrap(txt, width = 80, exdent = 4)
    nlines <- length(lines)
    if (nlines > 1) {
      nrs <- 1 : (nlines - 1)
      lines[nrs] <- paste(lines[nrs], "\\")
    }
    writeLines(c(lines, ""), con = con)
  }
  close(con)

  invisible()
}

#' Returns isismdl modules used in Fortran source file
#'
#' @param filename Character of length 1: the relative path of the Fortran
#' source file (relative to `src_dir`).
#' @param src_dir The directory with source files.
#' @param src_ext The extenstion of the Fortran source files.
#'
#' @return A character vector with the names of the used modules,
#' or `NULL` if the source file does not use isismdl modules.
#'
#' @noRd
read_used_modules <- function(filename, src_dir, src_ext) {

  lines <- readLines(file.path(src_dir, filename))
  if (length(lines) == 0) return(NULL)

  use_pattern <- "^\\s*use\\s+([a-z][a-z0-9_]*).*"
  use_lines <- grep(use_pattern, lines, value = TRUE, perl  = TRUE,
                    ignore.case = TRUE)
  if (length(use_lines) == 0) return(NULL)

  used_modules <- sub(use_pattern, "\\1", use_lines, perl = TRUE)
  used_modules <- unique(used_modules)

  # The used modules may include standard modules. Therefore check if the
  # source of the module exists in src_dir.
  module_src_files <- file.path(src_dir, paste0(used_modules, ".", src_ext))
  used_modules_isismdl <- used_modules[file.exists(module_src_files)]
  if (length(used_modules_isismdl) == 0) return(NULL)

  # Check that a Fortran source does not import its own module.
  src_name <- sub(paste0("\\.", src_ext, "$"), "", filename)
  if (src_name %in% used_modules_isismdl) {
    stop("f90 file imports its own module for ", filename)
  }

  # returns used modules in alphabetic order
  sort(used_modules_isismdl)
}

#' Returns a list with all dependencies of Fortran files on modules.
#'
#' @param filenames Character: filenames of Fortran files.
#' @param src_dir The directory with source files.
#' @param src_ext Extension of the Fortran file
#'
#' @returns A named list with the used modules.
#' @noRD
get_dep_list_f90 <- function(filenames, src_dir, src_ext) {

  deps <- lapply(filenames, FUN = read_used_modules, src_dir = src_dir,
                 src_ext = src_ext)
  names(deps) <- filenames

  # remove files without dependencies
  is_null <- sapply(deps, FUN = is.null)
  deps[!is_null]
}
